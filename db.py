import csv, json, sqlite3
from contextlib import contextmanager
from config import DATABASE_URL, DB_PATH


class DuplicateReceiptError(Exception):
    """Raised when a fuel receipt number already exists."""


_push_schema_ready = False


def _tbl(name):
    return ("public." if DATABASE_URL else "") + name


def _sql(text):
    """Write SQL with ? placeholders; PostgreSQL needs %s."""
    return text.replace("?", "%s") if DATABASE_URL else text


def _ensure_push_schema(c):
    """Tables for closed-app alerts. Created once per server start."""
    global _push_schema_ready
    if _push_schema_ready:
        return
    created = "TIMESTAMPTZ DEFAULT now()" if DATABASE_URL else "TEXT DEFAULT CURRENT_TIMESTAMP"
    c.execute(f"CREATE TABLE IF NOT EXISTS {_tbl('push_tokens')}(token TEXT PRIMARY KEY, created {created})")
    c.execute(f"CREATE TABLE IF NOT EXISTS {_tbl('run_tokens')}(run_id TEXT PRIMARY KEY, token TEXT)")
    c.execute(f"CREATE TABLE IF NOT EXISTS {_tbl('alert_state')}(run_id TEXT PRIMARY KEY, last_sent TEXT)")
    _push_schema_ready = True


@contextmanager
def conn():
    if DATABASE_URL:
        import psycopg

        with psycopg.connect(DATABASE_URL, sslmode="require", prepare_threshold=None) as c:
            c.execute("""CREATE TABLE IF NOT EXISTS public.events(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                run_id TEXT, t TEXT, at TEXT, data JSONB, receipt TEXT UNIQUE)""")
            _ensure_push_schema(c)
            yield c
        return

    c = sqlite3.connect(DB_PATH)
    try:
        c.execute("""CREATE TABLE IF NOT EXISTS events(
            id INTEGER PRIMARY KEY, run_id TEXT, t TEXT, at TEXT, data TEXT,
            receipt TEXT UNIQUE)""")
        _ensure_push_schema(c)
        with c:
            yield c
    finally:
        c.close()


def get_fuel_receipt(receipt_no):
    """Check if a fuel receipt already exists (case-insensitive and trimmed)."""
    if not receipt_no:
        return None
    r = str(receipt_no).strip()
    if not r:
        return None
    with conn() as c:
        table = "public.events" if DATABASE_URL else "events"
        if DATABASE_URL:
            row = c.execute(
                f"SELECT id, run_id, t, at, data, receipt FROM {table} WHERE t = 'fuel' AND UPPER(TRIM(receipt)) = UPPER(%s) LIMIT 1",
                (r,),
            ).fetchone()
        else:
            row = c.execute(
                f"SELECT id, run_id, t, at, data, receipt FROM {table} WHERE t = 'fuel' AND UPPER(TRIM(receipt)) = UPPER(?) LIMIT 1",
                (r,),
            ).fetchone()
    if not row:
        return None
    data = _decode_data(row[4])
    return {
        "id": row[0],
        "run_id": row[1],
        "t": row[2],
        "at": row[3],
        "data": data,
        "receipt": row[5],
    }


def add_event(run_id, t, at, data):
    """Raises a database unique-constraint error if a fuel receipt repeats."""
    receipt = (data or {}).get("receipt_no") if t == "fuel" else None
    if receipt:
        receipt = str(receipt).strip()
        if not receipt:
            receipt = None
        else:
            existing = get_fuel_receipt(receipt)
            if existing:
                raise DuplicateReceiptError(f"Fuel receipt {receipt} already exists")
    with conn() as c:
        if DATABASE_URL:
            import psycopg
            from psycopg.types.json import Jsonb

            try:
                cursor = c.execute(
                    "INSERT INTO public.events(run_id,t,at,data,receipt) VALUES(%s,%s,%s,%s,%s) RETURNING id",
                    (str(run_id), t, at, Jsonb(data), receipt),
                )
            except psycopg.errors.UniqueViolation as error:
                raise DuplicateReceiptError from error
        else:
            try:
                cursor = c.execute(
                    "INSERT INTO events(run_id,t,at,data,receipt) VALUES(?,?,?,?,?)",
                    (str(run_id), t, at, json.dumps(data), receipt),
                )
            except sqlite3.IntegrityError as error:
                raise DuplicateReceiptError from error
        return cursor.fetchone()[0] if DATABASE_URL else cursor.lastrowid


