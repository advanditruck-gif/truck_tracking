def _decode_data(value):
    return json.loads(value) if isinstance(value, str) else value


def migrate_sqlite_to_postgres(source_path):
    """Copy SQLite events to PostgreSQL, preserving IDs and rejecting conflicting rows."""
    source = sqlite3.connect(source_path)
    try:
        rows = source.execute(
            "SELECT id,run_id,t,at,data,receipt FROM events ORDER BY id"
        ).fetchall()
    finally:
        source.close()

    return _migrate_rows_to_postgres(rows)


def migrate_csv_to_postgres(source_path):
    """Import the CSV downloaded from the admin page into PostgreSQL."""
    rows = []
    with open(source_path, newline="", encoding="utf-8-sig") as source:
        for event in csv.DictReader(source):
            data = json.loads(event["Data"])
            receipt = (data or {}).get("receipt_no") if event["Type"] == "fuel" else None
            rows.append((
                int(event["ID"]),
                event["Run"],
                event["Type"],
                event["Recorded at"],
                data,
                receipt,
            ))
    return _migrate_rows_to_postgres(rows)


def _migrate_rows_to_postgres(rows):
    from psycopg.types.json import Jsonb

    with conn() as target:
        ids = [row[0] for row in rows]
        existing = {}
        if ids:
            for row in target.execute(
                "SELECT id,run_id,t,at,data,receipt FROM public.events WHERE id = ANY(%s)",
                (ids,),
            ).fetchall():
                existing[row[0]] = row

        imported = 0
        for row in rows:
            event_id, run_id, event_type, recorded_at, raw_data, receipt = row
            data = _decode_data(raw_data)
            if event_id in existing:
                old = existing[event_id]
                if (old[1], old[2], old[3], old[4], old[5]) != (
                    run_id, event_type, recorded_at, data, receipt
                ):
                    raise ValueError(f"Destination already has a different event with ID {event_id}.")
                continue
            target.execute(
                """INSERT INTO public.events(id,run_id,t,at,data,receipt)
                   VALUES(%s,%s,%s,%s,%s,%s)""",
                (event_id, run_id, event_type, recorded_at, Jsonb(data), receipt),
            )
            imported += 1

        target.execute(
            """SELECT setval(
                pg_get_serial_sequence('public.events', 'id'),
                COALESCE(MAX(id), 1),
                MAX(id) IS NOT NULL
            ) FROM public.events"""
        )
    return imported


# ---------- closed-app alerts ----------
def save_token(token):
    with conn() as c:
        c.execute(_sql(f"INSERT INTO {_tbl('push_tokens')}(token) VALUES(?) ON CONFLICT(token) DO NOTHING"), (token,))


def all_tokens():
    with conn() as c:
        rows = c.execute(f"SELECT token FROM {_tbl('push_tokens')}").fetchall()
    return [r[0] for r in rows]


def delete_tokens(tokens):
    with conn() as c:
        for token in tokens:
            c.execute(_sql(f"DELETE FROM {_tbl('push_tokens')} WHERE token = ?"), (token,))
            c.execute(_sql(f"DELETE FROM {_tbl('run_tokens')} WHERE token = ?"), (token,))


def link_run_token(run_id, token):
    """Remember which phone is doing this run, so only that driver gets the alert."""
    with conn() as c:
        c.execute(_sql(
            f"INSERT INTO {_tbl('run_tokens')}(run_id, token) VALUES(?, ?) "
            "ON CONFLICT(run_id) DO UPDATE SET token = EXCLUDED.token"), (str(run_id), token))


def run_token(run_id):
    with conn() as c:
        row = c.execute(_sql(f"SELECT token FROM {_tbl('run_tokens')} WHERE run_id = ?"), (str(run_id),)).fetchone()
    return row[0] if row else None


def active_run_locations():
    """(run_id, time of the latest location photo) for every run that has not been stopped."""
    events = _tbl("events")
    with conn() as c:
        rows = c.execute(
            f"SELECT e.run_id, MAX(e.at) FROM {events} e "
            "WHERE e.t = 'location' AND e.run_id <> 'None' "
            f"AND NOT EXISTS (SELECT 1 FROM {events} s WHERE s.run_id = e.run_id AND s.t = 'stop_km') "
            "GROUP BY e.run_id").fetchall()
    return [(r[0], r[1]) for r in rows]


def last_alert(run_id):
    with conn() as c:
        row = c.execute(_sql(f"SELECT last_sent FROM {_tbl('alert_state')} WHERE run_id = ?"), (str(run_id),)).fetchone()
    return row[0] if row else None


def set_last_alert(run_id, when_iso):
    with conn() as c:
        c.execute(_sql(
            f"INSERT INTO {_tbl('alert_state')}(run_id, last_sent) VALUES(?, ?) "
            "ON CONFLICT(run_id) DO UPDATE SET last_sent = EXCLUDED.last_sent"), (str(run_id), when_iso))