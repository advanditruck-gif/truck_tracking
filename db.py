import csv, json, sqlite3
from contextlib import contextmanager
from config import DATABASE_URL, DB_PATH


class DuplicateReceiptError(Exception):
    """Raised when a fuel receipt number already exists."""


@contextmanager
def conn():
    if DATABASE_URL:
        import psycopg

        with psycopg.connect(DATABASE_URL, sslmode="require", prepare_threshold=None) as c:
            c.execute("""CREATE TABLE IF NOT EXISTS public.events(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                run_id TEXT, t TEXT, at TEXT, data JSONB, receipt TEXT UNIQUE)""")
            yield c
        return

    c = sqlite3.connect(DB_PATH)
    try:
        c.execute("""CREATE TABLE IF NOT EXISTS events(
            id INTEGER PRIMARY KEY, run_id TEXT, t TEXT, at TEXT, data TEXT,
            receipt TEXT UNIQUE)""")
        with c:
            yield c
    finally:
        c.close()


def add_event(run_id, t, at, data):
    """Raises a database unique-constraint error if a fuel receipt repeats."""
    receipt = (data or {}).get("receipt_no") if t == "fuel" else None
    with conn() as c:
        if DATABASE_URL:
            import psycopg
            from psycopg.types.json import Jsonb

            try:
                cursor = c.execute(
                    "INSERT INTO public.events(run_id,t,at,data,receipt) VALUES(%s,%s,%s,%s,%s) RETURNING id",
                    (str(run_id), t, at, Jsonb(data), receipt),
                )
            except psycopg.errors.UniqueViolation as error:
                raise DuplicateReceiptError from error
        else:
            try:
                cursor = c.execute(
                    "INSERT INTO events(run_id,t,at,data,receipt) VALUES(?,?,?,?,?)",
                    (str(run_id), t, at, json.dumps(data), receipt),
                )
            except sqlite3.IntegrityError as error:
                raise DuplicateReceiptError from error
        return cursor.fetchone()[0] if DATABASE_URL else cursor.lastrowid


def all_events():
    with conn() as c:
        table = "public.events" if DATABASE_URL else "events"
        rows = c.execute(f"SELECT run_id,t,at,data FROM {table} ORDER BY id").fetchall()
    return [{"run": r[0], "t": r[1], "at": r[2], "d": _decode_data(r[3])} for r in rows]


def admin_events():
    with conn() as c:
        table = "public.events" if DATABASE_URL else "events"
        rows = c.execute(f"SELECT id,run_id,t,at,data FROM {table} ORDER BY id DESC").fetchall()
    return [{"id": r[0], "run": r[1], "t": r[2], "at": r[3], "d": _decode_data(r[4])} for r in rows]


def admin_event(event_id):
    with conn() as c:
        table = "public.events" if DATABASE_URL else "events"
        placeholder = "%s" if DATABASE_URL else "?"
        row = c.execute(
            f"SELECT id,run_id,t,at,data FROM {table} WHERE id = {placeholder}",
            (event_id,),
        ).fetchone()
    if not row:
        return None
    return {"id": row[0], "run": row[1], "t": row[2], "at": row[3], "d": _decode_data(row[4])}


def delete_event(event_id):
    with conn() as c:
        table = "public.events" if DATABASE_URL else "events"
        placeholder = "%s" if DATABASE_URL else "?"
        cursor = c.execute(f"DELETE FROM {table} WHERE id = {placeholder}", (event_id,))
        return cursor.rowcount > 0


def _decode_data(value):
    return json.loads(value) if isinstance(value, str) else value


def migrate_sqlite_to_postgres(source_path):
    """Copy SQLite events to PostgreSQL, preserving IDs and rejecting conflicting rows."""
    source = sqlite3.connect(source_path)
    try:
        rows = source.execute(
            "SELECT id,run_id,t,at,data,receipt FROM events ORDER BY id"
        ).fetchall()
    finally:
        source.close()

    return _migrate_rows_to_postgres(rows)


def migrate_csv_to_postgres(source_path):
    """Import the CSV downloaded from the admin page into PostgreSQL."""
    rows = []
    with open(source_path, newline="", encoding="utf-8-sig") as source:
        for event in csv.DictReader(source):
            data = json.loads(event["Data"])
            receipt = (data or {}).get("receipt_no") if event["Type"] == "fuel" else None
            rows.append((
                int(event["ID"]),
                event["Run"],
                event["Type"],
                event["Recorded at"],
                data,
                receipt,
            ))
    return _migrate_rows_to_postgres(rows)


def _migrate_rows_to_postgres(rows):
    from psycopg.types.json import Jsonb

    with conn() as target:
        ids = [row[0] for row in rows]
        existing = {}
        if ids:
            for row in target.execute(
                "SELECT id,run_id,t,at,data,receipt FROM public.events WHERE id = ANY(%s)",
                (ids,),
            ).fetchall():
                existing[row[0]] = row

        imported = 0
        for row in rows:
            event_id, run_id, event_type, recorded_at, raw_data, receipt = row
            data = _decode_data(raw_data)
            if event_id in existing:
                old = existing[event_id]
                if (old[1], old[2], old[3], old[4], old[5]) != (
                    run_id, event_type, recorded_at, data, receipt
                ):
                    raise ValueError(f"Destination already has a different event with ID {event_id}.")
                continue
            target.execute(
                """INSERT INTO public.events(id,run_id,t,at,data,receipt)
                   VALUES(%s,%s,%s,%s,%s,%s)""",
                (event_id, run_id, event_type, recorded_at, Jsonb(data), receipt),
            )
            imported += 1

        target.execute(
            """SELECT setval(
                pg_get_serial_sequence('public.events', 'id'),
                COALESCE(MAX(id), 1),
                MAX(id) IS NOT NULL
            ) FROM public.events"""
        )
    return imported
